/**
 * 일차별 색.
 *
 * 지도 마커·경로선과 일차 선택 탭이 같은 색을 써야 "1일차 = 주황" 이 눈에
 * 남습니다. 한 곳에서만 정의해 두 화면이 어긋나지 않게 합니다.
 */

/**
 * 부산 도시철도 호선 색을 일차 순서대로 씁니다.
 *
 * 1~4일차는 1~4호선, 5일차는 부산김해경전철 색입니다. 지도 위에 얹히는 색이라
 * 노선도 원색을 그대로 쓰지는 못하고 채도·명도만 조정했습니다.
 *
 * 두 가지를 함께 만족시켜야 합니다.
 * - 마커 안 검은 글자와 4.5:1 이상 → 실제 5.1~7.5:1
 * - 밝은 지도 타일과 1.6:1 이상   → 실제 1.8~2.8:1
 *
 * 1호선 주황(#F06A00)은 그대로도 두 기준을 통과해 값을 거의 유지했습니다.
 * 4호선 파랑(#217DCB)과 경전철 자주(#8B2A87)는 검은 글자 대비가 각각
 * 4.2:1, 2.4:1 이라 밝기를 올렸습니다.
 */
const DAY_COLORS = [
  "#F26A00", // 1일차 — 1호선 주황
  "#6FB92E", // 2일차 — 2호선 연두, 채도를 올려 브랜드 라임에 붙임
  "#B27C52", // 3일차 — 3호선 갈색
  "#3B90DB", // 4일차 — 4호선 파랑, 한 단계 밝게
  "#D555AE", // 5일차 — 부산김해경전철 자주, 두 단계 밝게
];

export const getDayColor = (dayNumber: number) =>
  DAY_COLORS[(dayNumber - 1) % DAY_COLORS.length];

/**
 * 일차 색 위에 얹는 글자색.
 *
 * 흰 글자는 다섯 색 모두에서 기준(4.5:1)에 못 미칩니다. 검은 글자는 전부
 * 통과하고, 서비스의 다른 글자와도 맞습니다.
 */
export const DAY_COLOR_FOREGROUND = "#191512";
