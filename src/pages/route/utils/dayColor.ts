/**
 * 일차별 색.
 *
 * 지도 마커·경로선과 일차 선택 탭이 같은 색을 써야 "1일차 = 라임" 이 눈에
 * 남습니다. 한 곳에서만 정의해 두 화면이 어긋나지 않게 합니다.
 */

/**
 * 최대 5일차까지 서로 구분되는 색.
 *
 * 핑크는 브랜드 색이고 라임은 primary500 을 선으로 쓸 수 있게 낮춘 값입니다.
 * 나머지는 색상환에서 충분히 떨어뜨려 골랐습니다.
 *
 * 두 가지를 함께 만족시켜야 합니다.
 * - 마커 안 검은 글자와 4.5:1 이상 → 실제 4.8~8.5:1
 * - 밝은 지도 타일과 1.6:1 이상   → 실제 1.7~3.0:1
 *
 * primary500(#81EA14)을 그대로 쓰면 지도 대비가 1.23:1 이라 선이 배경에 묻힙니다.
 */
const DAY_COLORS = [
  "#6BC70E", // 라임
  "#F26A00", // 주황
  "#FD1187", // 핑크 — secondary500
  "#4A7DFF", // 코발트
  "#00A99B", // 청록
];

export const getDayColor = (dayNumber: number) =>
  DAY_COLORS[(dayNumber - 1) % DAY_COLORS.length];

/**
 * 일차 색 위에 얹는 글자색.
 *
 * 흰 글자는 다섯 색 모두에서 기준(4.5:1)에 못 미칩니다. 검은 글자는 전부
 * 통과하고, 서비스의 다른 글자와도 맞습니다.
 */
export const DAY_COLOR_FOREGROUND = "#191512";
